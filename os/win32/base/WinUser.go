// MakeIntResourceW is a remake of Microsoft's macro MAKEINTRESOURCEW.
// #define MAKEINTRESOURCEW(i) ((LPWSTR)((ULONG_PTR)((WORD)(i))))
func MakeIntResourceW(id uint16) *uint16 {
	return (*uint16)(unsafe.Pointer(uintptr(id)))
}

