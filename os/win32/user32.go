// Functions which can not be generated by 'mkwinsyscall' tool while it is stupid.
//manual EnumWindows(lpEnumFunc t.WNDENUMPROC, lParam b.LPARAM)(ret b.BOOL, err error)[failretval==0] = user32.EnumWindows

func EnumWindows(lpEnumFunc t.WNDENUMPROC, lParam b.LPARAM) (ret b.BOOL, err error) {
	r0, _, e1 := syscall.SyscallN(procEnumWindows.Addr(), syscall.NewCallback(t.Convert_WNDENUMPROC_ToGolang(lpEnumFunc)), uintptr(lParam))
	ret = b.BOOL(r0)
	if ret == 0 {
		err = errnoErr(e1)
	}
	return
}
